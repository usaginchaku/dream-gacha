// Runs the production file:// app in a disposable browser profile, never the user's browser.
import assert from 'node:assert/strict';
import { mkdtemp, rm, readFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
if (!process.argv[2]) throw new Error('Pass the installed playwright package directory; optional screenshot path follows.');
const { chromium } = await import(pathToFileURL(path.join(process.argv[2], 'index.mjs')).href);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const profile = await mkdtemp(path.join(tmpdir(), 'dream-gacha-library-qa-'));
let browser;
try {
  browser = await chromium.launchPersistentContext(profile, { headless: true, channel: 'chrome', viewport: { width: 1280, height: 900 }, acceptDownloads: true });
  const page = await browser.newPage(), errors = [], requests = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('request', r => { if (/^https?:/.test(r.url())) requests.push(r.url()); });
  page.on('dialog', dialog => dialog.accept());
  await page.goto(pathToFileURL(path.join(root, 'index.html')).href);
  await page.waitForFunction(() => document.querySelector('#basePrompt').value.includes('0.1.3.2'));
  const standard = await page.locator('#basePrompt').inputValue();
  await page.locator('#basePrompt').fill(standard + '\n試験用の追加指示 <b>テキストとして表示</b>');
  await page.locator('#basePromptLabel').fill('試験版 A');
  await page.locator('#saveSettings').click();
  await page.locator('#buildPrompt').click();
  const assembled = await page.locator('#output').inputValue();
  await page.locator('#output').fill(assembled + '\n完成欄だけの追記');
  await page.locator('#openNovelSave').click();
  await page.waitForSelector('#novelBody', { state: 'visible' });
  const rawBody = '\n　動作確認の本文😀\n第二段落。\n';
  await page.evaluate(body => {
    const clipboardData = new DataTransfer(); clipboardData.setData('text/plain', 'テストの題名\n' + body);
    document.querySelector('#novelBody').dispatchEvent(new ClipboardEvent('paste', { clipboardData, bubbles: true, cancelable: true }));
  }, rawBody);
  assert.equal(await page.locator('#novelTitle').inputValue(), 'テストの題名');
  assert.equal(await page.locator('#novelBody').inputValue(), rawBody);
  await page.locator('#saveNovel').click();
  await page.waitForFunction(() => document.querySelector('#novelCount').textContent === '1本');
  let novels = await page.evaluate(() => novelAll());
  assert.equal(novels[0].body, rawBody); assert.equal(novels[0].promptSnapshot, assembled + '\n完成欄だけの追記');
  assert.equal(novels[0].snapshot.promptRecord.revision.baseText, standard + '\n試験用の追加指示 <b>テキストとして表示</b>');
  const frozenPrompt = JSON.stringify(novels[0].snapshot);
  await page.locator('[data-open-novel]').click();
  assert.match(await page.locator('#novelViewPromptInfo').textContent(), /試験版 A.*追加編集あり/);
  assert.equal(await page.locator('#novelViewPromptInfo b').count(), 0);
  await page.locator('#startNovelEdit').click();
  await page.locator('#novelEditTitle').fill('あとから変えたタイトル');
  await page.locator('#saveNovelEdit').click();
  await page.waitForFunction(() => document.querySelector('#novelViewTitle').textContent === 'あとから変えたタイトル');
  novels = await page.evaluate(() => novelAll()); assert.equal(JSON.stringify(novels[0].snapshot), frozenPrompt);
  await page.locator('summary').filter({ hasText: 'アノテーション用に書き出す' }).click();
  let waiting = page.waitForEvent('download'); await page.locator('#exportNovelJson').click();
  const json = JSON.parse(await readFile(await (await waiting).path(), 'utf8'));
  assert.equal(json.novel.title, 'あとから変えたタイトル'); assert.equal(json.prompt.text, assembled + '\n完成欄だけの追記');
  assert.equal(json.annotation.text, rawBody); assert.equal(json.prompt.record.revision.label, '試験版 A');
  waiting = page.waitForEvent('download'); await page.locator('#exportNovelBody').click();
  assert.equal(await readFile(await (await waiting).path(), 'utf8'), rawBody);
  await page.locator('#novelViewClose').click();
  await page.reload(); await page.locator('#tab-library').click();
  await page.waitForFunction(() => document.querySelector('#novelCount').textContent === '1本');
  assert.equal((await page.evaluate(() => novelAll()))[0].title, 'あとから変えたタイトル');
  await page.locator('#tab-gacha').click();
  await page.locator('#basePrompt').fill(standard + '\n次の版の指示');
  await page.locator('#basePromptLabel').fill('試験版 B');
  await page.locator('#saveSettings').click();
  const versions = await page.evaluate(() => JSON.parse(localStorage.getItem('dreamGachaSettings')).promptVersions);
  // First launch automatically rolls once, so the standard revision also exists.
  assert.equal(versions.length, 3);assert.equal(versions.filter(r => r.label === '試験版 A').length, 1);assert.equal(versions.filter(r => r.label === '試験版 B').length, 1);
  assert.equal(JSON.stringify((await page.evaluate(() => novelAll()))[0].snapshot), frozenPrompt);
  await page.locator('summary').filter({ hasText: '配布標準との差分・保存した版' }).click();
  await page.locator('#promptVersionHistory').selectOption(versions.find(r => r.label === '試験版 A').id);
  await page.locator('#usePromptVersion').click();
  assert.equal(await page.locator('#basePromptLabel').inputValue(), '試験版 A');
  await page.locator('#saveSettings').click();
  assert.equal((await page.evaluate(() => JSON.parse(localStorage.getItem('dreamGachaSettings')).promptVersions)).length, versions.length);
  const backup = await page.evaluate(() => fullBackupPayload());
  assert.equal(backup.data.promptVersions.length, versions.length); assert.equal(JSON.stringify(backup.data.novels[0].snapshot), frozenPrompt);
  await page.evaluate(data => restoreFullBackup(data), backup);
  assert.deepEqual(await page.evaluate(() => novelAll()), backup.data.novels);
  assert.deepEqual(await page.evaluate(() => JSON.parse(localStorage.getItem('dreamGachaSettings')).promptVersions), backup.data.promptVersions);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('#tab-library').click();
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.locator('[data-open-novel]').click();
  assert.ok(await page.evaluate(() => document.querySelector('.novel-dialog').getBoundingClientRect().width <= innerWidth));
  if (process.argv[3]) await page.screenshot({ path: process.argv[3] });
  assert.deepEqual(errors, []); assert.deepEqual(requests, []);
  console.log('PASS: production app paste, frozen prompt/version, title edit, TXT/JSON downloads, reload, history reuse, backup, 390px layout; no page errors or external requests');
} finally {
  if (browser) await browser.close();
  const checked = path.resolve(profile);
  if (path.dirname(checked) !== path.resolve(tmpdir()) || !path.basename(checked).startsWith('dream-gacha-library-qa-')) throw new Error('Unexpected QA cleanup path');
  await rm(checked, { recursive: true, force: true });
}
